/**
 * Returns a new sentence variety that is guaranteed to be DIFFERENT from currentEx1.
 */
export function getNextSentenceVariety(targetWord, currentEx1 = '', clipContext = null) {
  const norm = (targetWord || '').trim().toLowerCase();
  const pool = CURATED_SENTENCE_VARIETIES[norm];

  if (pool && pool.length > 0) {
    const candidates = pool.filter(v => v.ex1En.toLowerCase() !== (currentEx1 || '').toLowerCase());
    const list = candidates.length > 0 ? candidates : pool;
    const picked = list[Math.floor(Math.random() * list.length)];
    return { ...picked };
  }

  // No curated pool → caller resolves real sentences via /api/vocab/lookup (no placeholder templates)
  return null;
}

